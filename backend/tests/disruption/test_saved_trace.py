"""PII scan over the saved full-run trace (task 5.3).

`docs/trace-abc123.jsonl` is produced by `evals/save_trace.py` against the
real model (not generated by this test). This test only checks the
artifact that is committed: every line is valid JSON, and none of it
carries personal data or a raw source/event name.
"""

import json
from pathlib import Path

TRACE_PATH = Path(__file__).resolve().parents[3] / "docs" / "trace-abc123.jsonl"

FORBIDDEN = (
    "document_id",
    "12.345.678-9",
    "maria.silva@example.com",
    "8765 4321",
    "Silva",
    "LEGACY_MIRROR",
    "E-1012",
)


def test_saved_trace_exists_and_is_valid_json_lines():
    assert TRACE_PATH.exists(), f"{TRACE_PATH} is missing; run `python -m evals.save_trace` to produce it"
    lines = TRACE_PATH.read_text(encoding="utf-8").splitlines()
    assert lines, "the saved trace is empty"
    for line in lines:
        entry = json.loads(line)
        assert {"request_id", "agent", "tool", "args", "outcome", "latency_ms"} <= entry.keys()


def test_saved_trace_has_no_personal_data():
    text = TRACE_PATH.read_text(encoding="utf-8")
    for needle in FORBIDDEN:
        assert needle not in text, f"{needle!r} leaked into the saved trace"
